import assert from 'node:assert/strict'
import crypto from 'node:crypto'
import fs from 'node:fs'

export async function verifyOfferFlow({ admin, approver, panel1, panel2, call, ok, step, db, ui, seed, freshPage, expect }) {
  const stage = async () => {
    const [[row]] = await db.query('SELECT s.StageCode FROM recruitment_position_pipeline_instances p JOIN recruitment_position_stage_instances i ON i.Id=p.CurrentStageInstanceId JOIN recruitment_pipeline_stages s ON s.Id=i.PipelineStageId WHERE p.Id=904')
    return row.StageCode
  }
  assert.equal(await stage(), 'SIGNING_MOM', 'Selected interview cohort must advance despite another ATS-held application')
  await admin.goto(ui + '/recruitment/offers-and-pre-onboarding')
  const request = { applicationId: 901, offeredCtc: 1100000, currency: 'INR', proposedJoiningDate: new Date(Date.now() + 7 * 86400000).toISOString(), status: 'Draft', remarks: 'Isolated over-budget regression; never a real offer' }
  let offer = ok(await call(admin, '/api/recruitment/offers', request))
  offer = ok(await call(admin, `/api/recruitment/offers/${offer.id}/generate-letter`, {}))
  const release = () => call(admin, `/api/recruitment/offers/${offer.id}/status`, { status: 'Pending Candidate' })
  const early = await release(); assert.equal(early.ok, false); assert.match(early.body.error, /MoM|prerequisite/i)
  assert.equal((await call(admin, '/api/recruitment-orchestration/applications/901/candidate-actions', { applicationId: 901, offerId: offer.id, purposeCode: 'OFFER_RESPONSE' })).ok, false)
  // An old, already-issued link must also be rejected at submission time, not just creation.
  const token = crypto.randomBytes(24).toString('base64url')
  const [[pipeline]] = await db.query('SELECT CurrentStageInstanceId FROM recruitment_application_pipeline_instances WHERE ApplicationId=901')
  await db.query("UPDATE recruitment_offers SET Status='Pending Candidate' WHERE Id=?", [offer.id])
  await seed('recruitment_candidate_action_sessions', { Id: 9901, ClientId: 901, ApplicationId: 901, CandidateId: 901, PipelineStageInstanceId: pipeline.CurrentStageInstanceId, OfferId: offer.id, PurposeCode: 'OFFER_RESPONSE', TokenHash: crypto.createHash('sha256').update(token).digest('hex'), TokenCipherText: '', ExpiresAtUtc: new Date(Date.now() + 86400000), CreatedByUserId: 9001 })
  const guest = await freshPage()
  await guest.goto(ui + '/candidate-action/' + token)
  const refused = await call(guest, `/api/public/recruitment/actions/${token}`, { decision: 'Accepted' })
  assert.equal(refused.ok, false); assert.match(refused.body.error, /MoM|prerequisite/i)
  await db.query("UPDATE recruitment_candidate_action_sessions SET Status='Revoked',RevokedAtUtc=UTC_TIMESTAMP() WHERE Id=9901")
  await db.query("UPDATE recruitment_offers SET Status='Draft' WHERE Id=?", [offer.id])
  await step(admin, 'MoM gate blocks new release and legacy public acceptance links')

  const document = ok(await call(admin, '/api/recruitment/process-documents', { clientId: 901, hiringCaseId: 904, pipelineStageId: 9044, documentType: 'MOM', status: 'Prepared' }))
  assert.equal((await call(admin, `/api/recruitment/process-documents/${document.id}/signatures`, { signerName: 'Not a panel member', signatureMethod: 'Typed' })).ok, false)
  ok(await call(panel1, `/api/recruitment/process-documents/${document.id}/signatures`, { signerName: 'Test Panel One', signatureMethod: 'Typed' }))
  assert.equal(await stage(), 'SIGNING_MOM')
  ok(await call(panel2, `/api/recruitment/process-documents/${document.id}/signatures`, { signerName: 'Test Panel Two', signatureMethod: 'Typed' }))
  assert.equal(await stage(), 'NEGOTIATION_AND_MOM_TO_HR')
  await admin.goto(ui + '/recruitment/work-orders-and-sla')
  await step(admin, 'Two own MoM signatures automatically advance hiring into negotiation')
  const overBudget = await release(); assert.equal(overBudget.ok, false); assert.match(overBudget.body.error, /budget/i)
  await step(admin, '11 lakh release refused against approved 10 lakh despite higher salary max')
  offer = ok(await call(admin, '/api/recruitment/offers', { ...request, id: offer.id, offeredCtc: 1000000 }))
  offer = ok(await call(admin, `/api/recruitment/offers/${offer.id}/generate-letter`, {}))
  offer = ok(await release()); assert.equal(offer.status, 'Pending Approval')
  assert.equal(await stage(), 'HR_DIVISION_APPROVAL')
  async function approveResource(resourceType) {
    const tasks = ok(await call(approver, '/api/workflows/tasks/pending'))
    const task = tasks.find(t => t.resourceType === resourceType); assert(task, `Missing ${resourceType} task`)
    assert.equal((await call(admin, `/api/workflows/tasks/${task.id}/Approved`, { comment: 'Wrong actor' })).ok, false)
    ok(await call(approver, `/api/workflows/tasks/${task.id}/Approved`, { comment: 'Isolated synthetic approval' }))
  }
  await approveResource('RecruitmentOffer')
  assert.equal(await stage(), 'HR_DIVISION_APPROVAL')
  assert.equal((await release()).ok, false)
  await step(approver, 'Offer approval cannot bypass pending HR hiring-stage approval')
  await approveResource('RecruitmentPipelineTransition')
  assert.equal(await stage(), 'OFFER_ISSUANCE')
  offer = ok(await release()); assert.equal(offer.status, 'Pending Candidate')
  const actions = ok(await call(admin, '/api/recruitment-orchestration/applications/901/candidate-actions'))
  const action = actions.find(a => a.purposeCode === 'OFFER_RESPONSE' && a.status === 'Open'); assert(action?.actionToken)
  await guest.goto(ui + '/candidate-action/' + encodeURIComponent(action.actionToken))
  await expect(guest.getByRole('button', { name: 'Accept offer', exact: true })).toBeVisible()
  // Existing links must recheck a changed budget, including legacy offers without config.
  await db.query('UPDATE recruitment_open_positions SET BudgetAmount=900000 WHERE Id=901')
  await db.query('UPDATE recruitment_offers SET StageOfferConfigurationId=NULL WHERE Id=?', [offer.id])
  const staleBudget = await call(guest, `/api/public/recruitment/actions/${action.actionToken}`, { decision: 'Accepted' })
  assert.equal(staleBudget.ok, false); assert.match(staleBudget.body.error, /budget/i)
  await db.query('UPDATE recruitment_open_positions SET BudgetAmount=1000000 WHERE Id=901')
  await db.query('UPDATE recruitment_offers SET StageOfferConfigurationId=? WHERE Id=?', [offer.stageOfferConfigurationId, offer.id])
  await step(guest, 'Anonymous candidate sees offer only after MoM negotiation and both approvals')
  await guest.getByRole('button', { name: 'Accept offer', exact: true }).click()
  const response = guest.waitForResponse(r => r.url().includes('/api/public/recruitment/actions/') && r.request().method() === 'POST')
  await guest.getByRole('button', { name: 'Confirm acceptance', exact: true }).click()
  assert((await response).ok())
  await expect(guest.getByText('ACCEPTED', { exact: true })).toBeVisible()
  assert.equal(await stage(), 'CONVEY_JOINING_DATE')
  const [[saved]] = await db.query('SELECT Status FROM recruitment_offers WHERE Id=?', [offer.id]); assert.equal(saved.Status, 'Accepted')
  await step(guest, 'Candidate acceptance automatically advances hiring and candidate journey')
  const originalAttachment = offer.offerLetterAttachmentPublicId
  const finalTasks = ok(await call(approver, '/api/workflows/tasks/pending'))
  const finalTask = finalTasks.find(t => t.resourceType === 'RecruitmentFinalOffer' && t.resourceId === String(offer.id))
  assert(finalTask, 'Acceptance must create a real departmental approval task')
  assert.equal((await call(admin, `/api/workflows/tasks/${finalTask.id}/Approved`, { comment: 'Wrong departmental actor' })).ok, false)
  // Repeated requests reuse the same pending workflow instead of creating tasks or signing early.
  const pending = ok(await call(admin, `/api/recruitment/offers/${offer.id}/final-letter`, {}))
  assert.equal(pending.finalApprovalWorkflowInstanceId, finalTask.instanceId)
  assert.equal(pending.finalOfferLetterAttachmentPublicId, null)
  const reassign = await call(admin, '/api/recruitment/clients/901/final-offer-settings', { enabled: true, finalApproverUserId: 9001 })
  assert.equal(reassign.status, 400); assert.match(reassign.body.error, /pending final-letter approvals/i)
  await step(admin, 'Accepted offer waits for the assigned departmental approver; retries do not duplicate tasks')
  await db.query('UPDATE recruitment_offers SET OfferedCtc=900000 WHERE Id=?', [offer.id])
  const changedTerms = await call(approver, `/api/workflows/tasks/${finalTask.id}/Approved`, { comment: 'Synthetic final document approval; isolated test database only' })
  assert.equal(changedTerms.status, 409); assert.match(changedTerms.body.error, /terms or template differ/i)
  await db.query('UPDATE recruitment_offers SET OfferedCtc=? WHERE Id=?', [offer.offeredCtc, offer.id])
  const signed = ok(await call(admin, `/api/recruitment/offers/${offer.id}/final-letter`, {}))
  assert.equal(signed.status, 'Accepted')
  assert.equal(signed.offerLetterAttachmentPublicId, originalAttachment)
  assert(signed.finalOfferLetterAttachmentPublicId && signed.finalOfferLetterAttachmentPublicId !== originalAttachment)
  const repeated = ok(await call(admin, `/api/recruitment/offers/${offer.id}/final-letter`, {}))
  assert.equal(repeated.finalOfferLetterAttachmentPublicId, signed.finalOfferLetterAttachmentPublicId)
  const [[receipt]] = await db.query("SELECT COUNT(*) n FROM workflowhistory WHERE InstanceId=? AND Action='FinalDocumentGenerated'", [finalTask.instanceId])
  assert.equal(receipt.n, 1)
  const [[oldFile]] = await db.query('SELECT is_current current,is_deleted deleted FROM entity_attachments WHERE public_id=?', [originalAttachment])
  assert(oldFile.current && !oldFile.deleted, 'The original accepted PDF must remain available')
  await admin.goto(ui + '/recruitment/offers-and-pre-onboarding')
  await admin.getByRole('button', { name: /Final signed letter$/ }).click()
  await expect(admin.getByRole('button', { name: /Export PDF$/ })).toBeEnabled()
  const pdf = await admin.evaluate(async () => Array.from(new Uint8Array(await (await fetch(document.querySelector('iframe[title="Offer letter PDF preview"]').src)).arrayBuffer())))
  assert.equal(Buffer.from(pdf).subarray(0, 5).toString(), '%PDF-')
  fs.writeFileSync('.codex-validation/recruitment-workflows/portal/final-signed-offer-test.pdf', Buffer.from(pdf))
  const publicPdf = await guest.evaluate(async token => {
    const response = await fetch(`/api/public/recruitment/actions/${encodeURIComponent(token)}/offer-document`)
    if (!response.ok) throw new Error(`Final candidate PDF status ${response.status}`)
    return Array.from(new Uint8Array(await response.arrayBuffer()))
  }, action.actionToken)
  assert.deepEqual(Buffer.from(publicPdf), Buffer.from(pdf), 'Authorized candidate sees the same approved final PDF')
  assert.equal((await call(guest, `/api/public/recruitment/actions/${action.actionToken}invalid/offer-document`)).status, 404)
  const [[sessionExpiry]] = await db.query('SELECT ExpiresAtUtc FROM recruitment_candidate_action_sessions WHERE Id=?', [action.id])
  await db.query('UPDATE recruitment_candidate_action_sessions SET ExpiresAtUtc=DATE_SUB(UTC_TIMESTAMP(),INTERVAL 1 DAY) WHERE Id=?', [action.id])
  assert.equal((await call(guest, `/api/public/recruitment/actions/${action.actionToken}/offer-document`)).status, 404)
  await db.query('UPDATE recruitment_candidate_action_sessions SET ExpiresAtUtc=? WHERE Id=?', [sessionExpiry.ExpiresAtUtc, action.id])
  await step(admin, 'Final signed PDF is generated after departmental approval; original letter and acceptance preserved')
  // Explicit legacy Accepted record: no previous departmental workflow, like an
  // already-issued historical offer. Keep its original attachment untouched.
  await seed('recruitment_offers', { Id: 9902, ApplicationId: 901, ClientId: 901, OfferNumber: 'TEST-LEGACY-9902',
    OfferedCtc: offer.offeredCtc, Currency: offer.currency, ProposedJoiningDate: new Date(offer.proposedJoiningDate),
    Status: 'Accepted', OfferLetterAttachmentPublicId: originalAttachment, ApprovalPolicy: 'Direct', CreatedByUserId: 9001 })
  const legacy = ok(await call(admin, '/api/recruitment/offers/9902/final-letter', {}))
  assert.equal(legacy.finalApprovalStatus, 'Pending')
  const legacyTask = ok(await call(approver, '/api/workflows/tasks/pending')).find(t => t.instanceId === legacy.finalApprovalWorkflowInstanceId)
  assert(legacyTask)
  const [[uploadGrant]] = await db.query("SELECT COUNT(*) n FROM authuserroles ur JOIN authrolepermissions rp ON rp.RoleId=ur.RoleId JOIN authpermissions p ON p.Id=rp.PermissionId WHERE ur.UserId=9004 AND p.Code IN ('attachment.recruitment.upload','recruitment.manage','settings.manage','security.manage')")
  assert.equal(uploadGrant.n, 0, 'Departmental approver must have no general upload/admin grant')
  ok(await call(approver, `/api/workflows/tasks/${legacyTask.id}/Approved`, { comment: 'Existing accepted synthetic offer; departmental authorization' }))
  const legacySigned = ok(await call(admin, '/api/recruitment/offers?applicationId=901')).find(row => row.id === 9902)
  assert(legacySigned.finalOfferLetterAttachmentPublicId)
  assert.equal(legacySigned.offerLetterAttachmentPublicId, originalAttachment)
  assert.equal(legacySigned.status, 'Accepted')
  await approver.reload()
  await step(approver, 'Client-scoped departmental approval automatically signs existing accepted offer without admin rights')
}
