import assert from 'node:assert/strict'

export async function verifySigningSettings({ admin, approver, panel1, call, ok, step, db, seed, ui, expect }) {
  const url = '/api/recruitment/clients/901/final-offer-settings'
  assert.equal(ok(await call(admin, url)).source, 'Not configured', 'Fixture must not rely on server signatory settings')
  assert.equal((await call(approver, url)).status, 403)
  assert.equal((await call(panel1, url, { enabled: true, finalApproverUserId: 9002 })).status, 403)
  await seed('clients', { Id: 909, Name: 'OTHER TEST CLIENT', Code: 'OTHER-909' })
  await seed('authusers', { Id: 9005, Email: 'outside@example.invalid', DisplayName: 'Outside client', ClientId: 909, IsActive: true })
  await seed('authusers', { Id: 9006, Email: 'inactive@example.invalid', DisplayName: 'Inactive approver', ClientId: 901, IsActive: false })
  for (const id of [9005, 9006, null])
    assert.equal((await call(admin, url, { enabled: true, finalApproverUserId: id })).status, 400)
  const users = ok(await call(admin, '/api/recruitment/budget-approvers?clientId=901'))
  assert(users.some(row => row.id === 9004)); assert(!users.some(row => [9005, 9006].includes(row.id)))
  await admin.goto(ui + '/recruitment/offers-and-pre-onboarding')
  await admin.bringToFront()
  await admin.getByRole('button', { name: /Final offer signatory$/ }).click()
  const drawer = admin.locator('.ant-drawer-content:visible')
  await drawer.getByRole('combobox').first().click()
  await admin.getByText('TEST MODE — Isolated UIDAI', { exact: true }).last().click()
  await expect(drawer.getByRole('switch')).toBeVisible()
  await drawer.getByRole('switch').click()
  await drawer.getByRole('combobox').nth(1).click()
  await admin.getByText('Test Budget Approver · approver@example.invalid', { exact: true }).click()
  await drawer.screenshot({ path: '.codex-validation/recruitment-workflows/portal/final-signatory-settings.png' })
  await drawer.getByRole('button', { name: 'Save configuration', exact: true }).click()
  await expect(drawer).toHaveCount(0)
  const saved = ok(await call(admin, url))
  assert.equal(saved.source, 'Portal'); assert.equal(saved.enabled, true); assert.equal(saved.finalApproverUserId, 9004)
  assert.equal(ok(await call(admin, '/api/recruitment/clients/909/final-offer-settings')).enabled, false)
  const off = ok(await call(admin, url, { enabled: false, finalApproverUserId: 9004 }))
  assert.equal(off.enabled, false)
  ok(await call(admin, url, { enabled: true, finalApproverUserId: 9004 }))
  const [[audit]] = await db.query("SELECT COUNT(*) n FROM recruitment_audit WHERE EntityType='RecruitmentFinalOfferSettings' AND EntityId=901 AND ChangedByUserId=9001")
  assert.equal(audit.n, 3)
  await step(admin, 'Super-admin configures client signatory in portal; wrong-client inactive and unauthorized users refused')
}
