using System.Text.RegularExpressions;
using Payroll.API.Models;

namespace Payroll.API.Services;

// Held drafts are never inserted into the shared worker's Queued pool.
// This is a reviewed execution lane, not a new authorization or approval policy.
internal static class SelectedPayRunDraft
{
    internal const string HeldStatus = "AwaitingProcessing";

    internal static bool IsProcessableStatus(string status) => status is "Queued" or HeldStatus;

    internal static void RequireCreation(CreatePayRunRequest request, SelectedRunRuntime runtime)
    {
        if (!runtime.Safe) throw new SelectedPayRunConflictException("Selected draft creation requires migrations and global background workers disabled and outbound delivery suppressed. No payroll request was saved.");
        if (request.ClientId <= 0 || !Regex.IsMatch(request.PayPeriod ?? "", @"^\d{4}-(0[1-9]|1[0-2])$") || request.TotalWorkingDays is < 1 or > 31)
            throw new SelectedPayRunConflictException("Select the exact client, pay period and 1 to 31 working-day divisor before creating a selected draft.");
        if (request.RunType != "Regular") throw new SelectedPayRunConflictException("Selected draft creation supports Regular payroll only.");
        if (request.IncludedEmployeeIds is null || request.ExcludedEmployeeIds is null || request.AdjustmentIds is null || request.AttendanceGroupIds is null
            || request.IncludedEmployeeIds.Count == 0 || request.IncludedEmployeeIds.Any(id => id <= 0)
            || request.IncludedEmployeeIds.Distinct().Count() != request.IncludedEmployeeIds.Count || request.ExcludedEmployeeIds.Count > 0)
            throw new SelectedPayRunConflictException("An explicit unique employee selection without exclusions is required. No implicit all-employees or partial scope is saved.");
        if (request.AdjustmentIds.Any(id=>id<=0) || request.AdjustmentIds.Distinct().Count()!=request.AdjustmentIds.Count
            || request.SelectedAdjustmentReviews is { Count: > 0 } || request.SourceReviewAttestation is not null)
            throw new SelectedPayRunConflictException("Select unique positive existing adjustment IDs; source/business review snapshots are generated by the server, never supplied by the caller.");
        var groups = Groups(request);
        if (groups.Length == 0 || groups.Any(id => id <= 0) || groups.Distinct().Count() != groups.Length
            || request.AttendanceGroupId > 0 && !groups.Contains(request.AttendanceGroupId)
            || string.IsNullOrWhiteSpace(request.AttendancePolicyBatchId) || request.AttendancePolicyBatchId.Length > 64)
            throw new SelectedPayRunConflictException("Select an explicit attendance policy batch and its exact policy groups for this client.");
        if (request.RunName?.Length > 120 || request.Reason?.Length > 500)
            throw new SelectedPayRunConflictException("The run name or reason exceeds the existing payroll storage limit.");
        if (request.PayDate.ToString("yyyy-MM") != request.PayPeriod)
            throw new SelectedPayRunConflictException("The selected payroll date must belong to the reviewed pay period.");
    }

    internal static int[] Groups(CreatePayRunRequest request) => request.AttendanceGroupIds.Count > 0
        ? request.AttendanceGroupIds.ToArray() : request.AttendanceGroupId > 0 ? [request.AttendanceGroupId] : [];

    internal static void RequireExactSelection(CreatePayRunRequest request, IReadOnlyCollection<int> eligible,
        IReadOnlyCollection<int> policyMembers, IReadOnlyCollection<int> covered, long approvedAdjustments, bool sourceAdjustmentsVerified=false)
    {
        if (!request.IncludedEmployeeIds.All(eligible.Contains))
            throw new SelectedPayRunConflictException("A selected employee is missing, outside this client or ineligible in this period. The request will not silently shrink.");
        if (!request.IncludedEmployeeIds.All(policyMembers.Contains))
            throw new SelectedPayRunConflictException("A selected employee is outside the reviewed attendance policy groups. Review the exact selection.");
        if (covered.Count > 0) throw new SelectedPayRunConflictException("Selected employees already have a Regular payroll result for this client and month. Review the retained run; no duplicate draft was saved.");
        if (approvedAdjustments > 0 && (!sourceAdjustmentsVerified || approvedAdjustments!=request.AdjustmentIds.Count))
            throw new SelectedPayRunConflictException("Applicable approved adjustments need an exact server-verified EXCEL_SETUP source review. No adjustment was applied or reset and no draft was saved.");
    }
}
