-- Schema-only owned synthetic fixture; canonical attachment/notification table definitions. No startup seed or backfill.
CREATE TABLE IF NOT EXISTS entity_attachments (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    public_id CHAR(36) NOT NULL,
    client_id INT NOT NULL,
    attachment_attribute_id BIGINT NOT NULL,
    field_configuration_id BIGINT NOT NULL,
    storage_server_id BIGINT NOT NULL,
    entity_type VARCHAR(60) NOT NULL,
    entity_id BIGINT NOT NULL,
    original_file_name VARCHAR(255) NOT NULL,
    stored_file_name VARCHAR(120) NOT NULL,
    storage_key VARCHAR(700) NOT NULL,
    file_extension VARCHAR(20) NOT NULL,
    declared_mime_type VARCHAR(150) NOT NULL DEFAULT '',
    detected_mime_type VARCHAR(150) NOT NULL,
    file_size_bytes BIGINT NOT NULL,
    sha256_hash CHAR(64) NOT NULL,
    version_number INT NOT NULL DEFAULT 1,
    document_number VARCHAR(180) NOT NULL DEFAULT '',
    issue_date DATE NULL,
    expiry_date DATE NULL,
    verification_status VARCHAR(30) NOT NULL DEFAULT 'NotRequired',
    verified_by_user_id INT NULL,
    verified_at_utc DATETIME(6) NULL,
    rejection_reason VARCHAR(500) NOT NULL DEFAULT '',
    malware_scan_status VARCHAR(30) NOT NULL DEFAULT 'NotScanned',
    malware_scanned_at_utc DATETIME(6) NULL,
    is_current BOOLEAN NOT NULL DEFAULT TRUE,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    uploaded_by_user_id INT NOT NULL,
    uploaded_by_external_subject_id BIGINT NULL,
    uploaded_at_utc DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    deleted_by_user_id INT NULL,
    deleted_at_utc DATETIME(6) NULL,
    UNIQUE KEY UX_entity_attachments_public_id (public_id),
    INDEX IX_entity_attachments_entity (client_id, entity_type, entity_id, is_current, is_deleted),
    INDEX IX_entity_attachments_field (field_configuration_id, entity_type, entity_id),
    INDEX IX_entity_attachments_storage (storage_server_id),
    INDEX IX_entity_attachments_expiry (expiry_date, is_current, is_deleted),
    INDEX IX_entity_attachments_hash (sha256_hash)
);
CREATE TABLE IF NOT EXISTS notification_queue (
    Id BIGINT PRIMARY KEY AUTO_INCREMENT,
    RuleId BIGINT NULL,
    EventCode VARCHAR(120) NOT NULL,
    ResourceType VARCHAR(100) NOT NULL,
    ResourceId VARCHAR(120) NOT NULL,
    ClientId INT NULL,
    ToJson JSON NOT NULL,
    CcJson JSON NOT NULL,
    BccJson JSON NOT NULL,
    Subject VARCHAR(500) NOT NULL,
    BodyHtml MEDIUMTEXT NOT NULL,
    Status VARCHAR(30) NOT NULL DEFAULT 'Pending',
    RetryCount INT NOT NULL DEFAULT 0,
    ErrorMessage TEXT NULL,
    CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    SentAt DATETIME NULL,
    INDEX IX_NotificationQueue_Status (Status, CreatedAt),
    INDEX IX_NotificationQueue_Resource (ResourceType, ResourceId)
);
CREATE TABLE IF NOT EXISTS notification_logs (
    Id BIGINT PRIMARY KEY AUTO_INCREMENT,
    QueueId BIGINT NOT NULL,
    EventCode VARCHAR(120) NOT NULL,
    ResourceType VARCHAR(100) NOT NULL,
    ResourceId VARCHAR(120) NOT NULL,
    Recipient VARCHAR(220) NOT NULL,
    Status VARCHAR(30) NOT NULL,
    ProviderMessageId VARCHAR(220) NOT NULL DEFAULT '',
    ErrorMessage TEXT NULL,
    CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX IX_NotificationLogs_Queue (QueueId),
    INDEX IX_NotificationLogs_Resource (ResourceType, ResourceId)
);
CREATE TABLE IF NOT EXISTS notification_queue_attachments (
    Id BIGINT PRIMARY KEY AUTO_INCREMENT,
    QueueId BIGINT NOT NULL,
    EntityAttachmentId BIGINT NOT NULL,
    CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY UX_NotificationQueueAttachment (QueueId, EntityAttachmentId),
    INDEX IX_NotificationQueueAttachment_Entity (EntityAttachmentId),
    CONSTRAINT FK_NotificationQueueAttachment_Queue FOREIGN KEY (QueueId) REFERENCES notification_queue(Id) ON DELETE CASCADE,
    CONSTRAINT FK_NotificationQueueAttachment_Entity FOREIGN KEY (EntityAttachmentId) REFERENCES entity_attachments(id)
);